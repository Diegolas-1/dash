#!/usr/bin/env node
'use strict';
// Writes tv/serverapp/service/lights.js (gitignored) with the lights provider and API key.
// Usage: GOVEE_API_KEY=... node tv/tools/set-lights.js            -> provider govee
//        node tv/tools/set-lights.js --mock                       -> back to the built-in sample lights
var fs = require('fs');
var path = require('path');
var OUT = path.join(__dirname, '..', 'serverapp', 'service', 'lights.js');
var mock = process.argv.indexOf('--mock') > 0;
var key = process.env.GOVEE_API_KEY || '';
if (!mock && !key) { console.error('Set GOVEE_API_KEY in the environment (never paste it in chat), or pass --mock.'); process.exit(1); }
var cfg = mock ? { provider: 'mock' } : { provider: 'govee', apiKey: key };
fs.writeFileSync(OUT, '// generated by tv/tools/set-lights.js - do not commit\nmodule.exports = ' + JSON.stringify(cfg, null, 2) + ';\n', { mode: 384 });
console.log('Wrote ' + path.relative(process.cwd(), OUT) + ' (' + cfg.provider + ')');
