#!/usr/bin/env node
'use strict';
// Writes tv/<app>/service/auth.js (scrypt hash) for an app's phone web page.
// Usage: DASH_PASSWORD=... node tv/tools/set-password.js [--app homeapp|torrentapp]
//        node tv/tools/set-password.js [--app ...]          (prompts)
var crypto = require('crypto');
var fs = require('fs');
var path = require('path');
var readline = require('readline');

var appArg = process.argv.indexOf('--app');
var APP = appArg > 0 ? process.argv[appArg + 1] : 'homeapp';
if (['homeapp', 'torrentapp'].indexOf(APP) < 0) {
  console.error('--app must be homeapp or torrentapp');
  process.exit(1);
}
var OUT = path.join(__dirname, '..', APP, 'service', 'auth.js');
var PARAMS = { N: 16384, r: 8, p: 1 };

function write(pw) {
  if (!pw || pw.length < 8) {
    console.error('Password must be at least 8 characters.');
    process.exit(1);
  }
  var salt = crypto.randomBytes(16);
  var hash = crypto.scryptSync(pw, salt, 32, PARAMS);
  var body = '// generated by tv/tools/set-password.js - do not commit\nmodule.exports = ' + JSON.stringify({
    salt: salt.toString('hex'), hash: hash.toString('hex'), N: PARAMS.N, r: PARAMS.r, p: PARAMS.p
  }, null, 2) + ';\n';
  fs.writeFileSync(OUT, body, { mode: 384 });
  console.log('Wrote ' + path.relative(process.cwd(), OUT));
}

function prompt(question, cb) {
  var rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
  rl._writeToOutput = function (s) { if (s.indexOf(question) === 0) rl.output.write(s); };
  rl.question(question, function (answer) { rl.close(); process.stdout.write('\n'); cb(answer); });
}

if (process.env.DASH_PASSWORD) {
  write(process.env.DASH_PASSWORD);
} else {
  prompt('Upload site password: ', function (a) {
    prompt('Repeat: ', function (b) {
      if (a !== b) { console.error('Passwords do not match.'); process.exit(1); }
      write(a);
    });
  });
}
